//! Typed IR -> Rust source (a Cargo crate depending on `scrust-runtime`).

mod expr;

use expr::{cast, f64_lit, str_lit, val_lit, Cx, E, RT};
use scrust_analysis::{Analysis, Node, Owner, Repr};
use scrust_ir::*;
use scrust_sb3::Project;
use scrust_value::{ToStr, Value};
use std::fmt::Write as _;

#[derive(Clone, Debug)]
pub struct GenOptions {
    pub crate_name: String,
    /// Absolute path of the scrust `crates/` directory (path dependencies).
    pub crates_dir: String,
    /// Headless build: no window, no embedded assets.
    pub headless: bool,
    pub warp_timer: bool,
    pub opt_level: u8,
    pub codegen_units: u32,
    /// Default frames per second baked into the program.
    pub fps: f64,
    pub turbo: bool,
    /// Build a `cdylib` for the browser host instead of a native binary.
    pub wasm: bool,
    /// Load assets from an `assets/` directory at run time instead of embedding them.
    pub external_assets: bool,
    /// Bodies longer than this many generated lines are split into part functions (3.3).
    pub max_fn_lines: usize,
}

pub struct Output {
    /// (relative path, contents)
    pub files: Vec<(String, String)>,
    /// Asset files (md5ext) the crate expects under `assets/`.
    pub assets: Vec<String>,
}

pub struct Gen<'a> {
    pub project: &'a Project,
    pub program: &'a Program,
    pub an: &'a Analysis,
    pub opts: &'a GenOptions,
    out: String,
    indent: usize,
    tmp: usize,
    /// Part functions produced by splitting long bodies.
    pending: String,
    /// Layer-2 flow types (§8.5): what a dynamically stored variable is known
    /// to hold at the current program point of the function being emitted.
    pub flow: std::collections::HashMap<VarId, scrust_analysis::Ty>,
}

/// What follows a statement list.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Tail {
    /// More statements of the same function.
    No,
    /// The end of a loop body.
    Loop,
    /// The end of the function body.
    Fn,
}

struct FnCx {
    cx: Cx,
    warp: bool,
    is_async: bool,
    /// Control-structure nesting depth of the statement being emitted.
    depth: u8,
    /// Is a `{ let w = world();` block currently open?
    w_open: bool,
    is_proc: bool,
    /// Emitting a part function: early exits return `Some(..)`.
    in_part: bool,
}

pub fn generate(project: &Project, program: &Program, an: &Analysis, opts: &GenOptions) -> Output {
    let mut g = Gen { project, program, an, opts, out: String::new(), indent: 0, tmp: 0, pending: String::new(), flow: Default::default() };
    let mut files = Vec::new();
    let mut assets = Vec::new();
    let mut main = String::new();
    main.push_str("// Generated by scrust. Do not edit.\n#![allow(warnings)]\n\nuse scrust_runtime::jstr;\nuse scrust_runtime::prelude::*;\n\n");
    for ti in 0..program.targets.len() {
        let _ = writeln!(main, "mod sprite_{ti};\npub use sprite_{ti}::*;");
    }
    main.push_str(
        "\n/// `Cast.toNumber` on a number: NaN becomes 0.\n#[inline(always)]\npub fn nn(x: f64) -> f64 {\n    if x.is_nan() {\n        0.0\n    } else {\n        x\n    }\n}\n\n",
    );
    main.push_str(&g.program_def(&mut assets));
    if opts.wasm {
        main.push_str("\nscrust_player::web_exports!(program, default_options);\n");
        files.push(("src/lib.rs".to_string(), main));
    } else {
        if opts.headless {
            main.push_str("\nfn main() {\n    scrust_runtime::cli::main(program(), default_options());\n}\n");
        } else {
            main.push_str("\nfn main() {\n    scrust_player::main(program(), default_options());\n}\n");
        }
        files.push(("src/main.rs".to_string(), main));
    }
    for ti in 0..program.targets.len() {
        files.push((format!("src/sprite_{ti}.rs"), g.sprite_module(ti)));
    }
    files.push(("Cargo.toml".to_string(), g.cargo_toml()));
    Output { files, assets }
}

fn repr_ty(r: Repr) -> &'static str {
    match r {
        Repr::F64 => "f64",
        Repr::Bool => "bool",
        Repr::Str => "JsStr",
        Repr::Val => "Value",
    }
}

fn rust_str(s: &str) -> String {
    format!("{:?}", s)
}

impl<'a> Gen<'a> {
    fn line(&mut self, s: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(s);
        self.out.push('\n');
    }

    fn fresh(&mut self) -> usize {
        self.tmp += 1;
        self.tmp
    }

    fn cargo_toml(&self) -> String {
        let o = self.opts;
        let mut s = format!(
            "[package]\nname = {:?}\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[workspace]\n\n[dependencies]\nscrust-runtime = {{ path = {:?} }}\n",
            o.crate_name,
            format!("{}/scrust-runtime", o.crates_dir)
        );
        if o.wasm {
            let _ = writeln!(s, "scrust-player = {{ path = {:?}, features = [\"embedded-font\"] }}", format!("{}/scrust-player", o.crates_dir));
            s.push_str("\n[lib]\ncrate-type = [\"cdylib\"]\n");
        } else if !o.headless {
            let _ = writeln!(s, "scrust-player = {{ path = {:?} }}", format!("{}/scrust-player", o.crates_dir));
        }
        let _ = write!(
            s,
            "\n[profile.release]\nopt-level = {}\ncodegen-units = {}\npanic = \"abort\"\ndebug = false\n\n[profile.dev]\nopt-level = 1\n",
            o.opt_level, o.codegen_units
        );
        s
    }

    // ------------------------------------------------------------ program def

    fn program_def(&mut self, assets: &mut Vec<String>) -> String {
        let p = self.program;
        let mut s = String::new();
        let o = self.opts;
        let _ = writeln!(
            s,
            "pub fn default_options() -> Options {{\n    Options {{ fps: {}, turbo: {}, warp_timer: {}, ..Options::default() }}\n}}\n",
            f64_lit(o.fps),
            o.turbo,
            o.warp_timer
        );
        s.push_str("pub fn program() -> ProgramDef {\n    ProgramDef {\n        sprites: vec![\n");
        for (ti, t) in p.targets.iter().enumerate() {
            let src = &self.project.targets[ti];
            let _ = writeln!(s, "            SpriteDef {{\n                name: {},\n                is_stage: {},", rust_str(&t.name), t.is_stage);
            s.push_str("                costumes: vec![\n");
            for c in &src.costumes {
                let data = if o.headless {
                    "&[]".to_string()
                } else if o.external_assets {
                    assets.push(c.md5ext.clone());
                    format!("scrust_runtime::load_asset({})", rust_str(&c.md5ext))
                } else {
                    assets.push(c.md5ext.clone());
                    format!("include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/assets/\", {}))", rust_str(&c.md5ext))
                };
                let _ = writeln!(
                    s,
                    "                    CostumeDef {{ name: {}, md5ext: {}, data_format: {}, data: {}, bitmap_resolution: {}, center_x: {}, center_y: {} }},",
                    rust_str(&c.name),
                    rust_str(&c.md5ext),
                    rust_str(&c.data_format),
                    data,
                    f64_lit(c.bitmap_resolution),
                    f64_lit(c.rotation_center_x),
                    f64_lit(c.rotation_center_y)
                );
            }
            s.push_str("                ],\n                sounds: vec![\n");
            for c in &src.sounds {
                let data = if o.headless {
                    "&[]".to_string()
                } else if o.external_assets {
                    assets.push(c.md5ext.clone());
                    format!("scrust_runtime::load_asset({})", rust_str(&c.md5ext))
                } else {
                    assets.push(c.md5ext.clone());
                    format!("include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/assets/\", {}))", rust_str(&c.md5ext))
                };
                let _ = writeln!(
                    s,
                    "                    SoundDef {{ name: {}, md5ext: {}, data_format: {}, data: {}, rate: {}, sample_count: {} }},",
                    rust_str(&c.name),
                    rust_str(&c.md5ext),
                    rust_str(&c.data_format),
                    data,
                    f64_lit(c.rate),
                    f64_lit(c.sample_count)
                );
            }
            s.push_str("                ],\n                scripts: vec![\n");
            for (si, sc) in t.scripts.iter().enumerate() {
                let (kind, field, msg) = match &sc.hat {
                    Hat::FlagClicked => ("Flag", String::new(), 0),
                    Hat::KeyPressed(k) => ("Key", k.clone(), 0),
                    Hat::SpriteClicked => ("SpriteClicked", String::new(), 0),
                    Hat::StageClicked => ("StageClicked", String::new(), 0),
                    Hat::BackdropSwitchesTo(b) => ("Backdrop", b.clone(), 0),
                    Hat::GreaterThan { .. } => ("Greater", String::new(), 0),
                    Hat::BroadcastReceived(m) => ("Broadcast", String::new(), *m),
                    Hat::StartAsClone => ("Clone", String::new(), 0),
                    Hat::TouchingObject(_) => ("Touching", String::new(), 0),
                };
                let pred = if sc.hat.is_edge_activated() { format!("Some(t{ti}_s{si}_pred)") } else { "None".to_string() };
                let _ = writeln!(
                    s,
                    "                    ScriptDef {{ kind: HatKind::{}, field: {}, msg: {}, restart: {}, start: t{ti}_s{si}, pred: {} }},",
                    kind,
                    rust_str(&field),
                    msg,
                    sc.hat.restarts_existing(),
                    pred
                );
            }
            let rs = match src.rotation_style.as_str() {
                "left-right" => "LeftRight",
                "don't rotate" => "DontRotate",
                _ => "AllAround",
            };
            let _ = writeln!(
                s,
                "                ],\n                new_locals: new_l{ti},\n                x: {}, y: {}, size: {}, direction: {}, visible: {}, draggable: {}, costume: {}, rotation_style: RotationStyle::{}, volume: {},\n            }},",
                f64_lit(src.x),
                f64_lit(src.y),
                f64_lit(src.size),
                f64_lit(src.direction),
                src.visible,
                src.draggable,
                src.current_costume,
                rs,
                f64_lit(src.volume)
            );
        }
        s.push_str("        ],\n        messages: vec![");
        for m in &p.messages {
            let _ = write!(s, "{}, ", rust_str(m));
        }
        s.push_str("],\n        broadcast_lookup: vec![");
        for (n, m) in &p.broadcast_lookup {
            let _ = write!(s, "({}, {}), ", rust_str(n), m);
        }
        s.push_str("],\n        monitors: vec![\n");
        for m in &self.project.monitors {
            if let Some(def) = self.monitor_def(m) {
                s.push_str(&def);
            }
        }
        s.push_str("        ],\n    }\n}\n");
        s
    }

    fn monitor_def(&self, m: &scrust_sb3::Monitor) -> Option<String> {
        let p = self.program;
        let sprite = match &m.sprite_name {
            Some(n) => p.targets.iter().position(|t| !t.is_stage && t.name == *n)?,
            None => 0,
        };
        let param = |k: &str| m.params.iter().find(|(n, _)| n == k).map(|(_, v)| v.clone());
        let (index, label, extra) = match m.opcode.as_str() {
            "data_variable" => {
                let name = param("VARIABLE")?;
                let t = &p.targets[sprite];
                let i = t.vars.iter().position(|v| v.id == m.id).or_else(|| t.vars.iter().position(|v| v.name == name))?;
                (i, name, String::new())
            }
            "data_listcontents" => {
                let name = param("LIST")?;
                let t = &p.targets[sprite];
                let i = t.lists.iter().position(|v| v.id == m.id).or_else(|| t.lists.iter().position(|v| v.name == name))?;
                (i, name, String::new())
            }
            op => {
                let extra = m.params.first().map(|(_, v)| v.clone()).unwrap_or_default();
                let label = match op {
                    "motion_xposition" => "x position".to_string(),
                    "motion_yposition" => "y position".to_string(),
                    "motion_direction" => "direction".to_string(),
                    "looks_size" => "size".to_string(),
                    "looks_costumenumbername" => format!("costume {}", extra),
                    "looks_backdropnumbername" => format!("backdrop {}", extra),
                    "sound_volume" => "volume".to_string(),
                    "sensing_answer" => "answer".to_string(),
                    "sensing_loudness" => "loudness".to_string(),
                    "sensing_timer" => "timer".to_string(),
                    "sensing_username" => "username".to_string(),
                    "sensing_current" => match extra.to_lowercase().as_str() {
                        "dayofweek" => "day of week".to_string(),
                        other => other.to_string(),
                    },
                    other => other.to_string(),
                };
                (0, label, extra)
            }
        };
        let label = if sprite != 0 { format!("{}: {}", p.targets[sprite].name, label) } else { label };
        Some(format!(
            "            MonitorDef {{ id: {}, opcode: {}, mode: {}, label: {}, sprite: {}, index: {}, param: {}, x: {}, y: {}, width: {}, height: {}, visible: {}, slider_min: {}, slider_max: {}, is_discrete: {} }},\n",
            rust_str(&m.id),
            rust_str(&m.opcode),
            rust_str(&m.mode),
            rust_str(&label),
            sprite,
            index,
            rust_str(&extra),
            f64_lit(m.x),
            f64_lit(m.y),
            f64_lit(m.width),
            f64_lit(m.height),
            m.visible,
            f64_lit(m.slider_min),
            f64_lit(m.slider_max),
            m.is_discrete
        ))
    }

    // ----------------------------------------------------------- sprite module

    fn sprite_module(&mut self, ti: usize) -> String {
        self.out.clear();
        self.indent = 0;
        let t = &self.program.targets[ti];
        self.line("// Generated by scrust. Do not edit.");
        self.line("use crate::*;");
        self.line("use scrust_runtime::jstr;");
        self.line("use scrust_runtime::prelude::*;");
        self.line("use std::future::Future;");
        self.line("use std::pin::Pin;");
        self.line("");
        // Variable storage.
        self.line("#[derive(Clone)]");
        self.line(&format!("pub struct L{ti} {{"));
        for (i, v) in t.vars.iter().enumerate() {
            let r = self.an.repr(Node::Var(VarId { target: ti, index: i }));
            self.line(&format!("    /// {}", v.name.replace('\n', " ")));
            self.line(&format!("    pub v{i}: {},", repr_ty(r)));
        }
        for (i, l) in t.lists.iter().enumerate() {
            let r = self.an.repr(Node::List(ListId { target: ti, index: i }));
            self.line(&format!("    /// {}", l.name.replace('\n', " ")));
            self.line(&format!("    pub l{i}: List<{}>,", repr_ty(r)));
        }
        self.line("}");
        self.line("");
        self.line(&format!("pub fn new_l{ti}() -> Box<dyn Locals> {{"));
        self.line(&format!("    Box::new(L{ti} {{"));
        for (i, v) in t.vars.iter().enumerate() {
            let r = self.an.repr(Node::Var(VarId { target: ti, index: i }));
            let init = E::lit(v.init.clone()).as_repr(r);
            self.line(&format!("        v{i}: {init},"));
        }
        for (i, l) in t.lists.iter().enumerate() {
            let r = self.an.repr(Node::List(ListId { target: ti, index: i }));
            let items: Vec<String> = l.init.iter().map(|v| E::lit(v.clone()).as_repr(r)).collect();
            self.line(&format!("        l{i}: List::new(vec![{}]),", items.join(", ")));
        }
        self.line("    })");
        self.line("}");
        self.line("");
        self.line(&format!("impl Locals for L{ti} {{"));
        self.line("    fn clone_box(&self) -> Box<dyn Locals> { Box::new(self.clone()) }");
        self.line("    fn as_any(&self) -> &dyn std::any::Any { self }");
        self.line("    fn as_any_mut(&mut self) -> &mut dyn std::any::Any { self }");
        self.line("    fn var_by_name(&self, name: &str) -> Option<Value> {");
        self.line("        match name {");
        let mut seen = std::collections::HashSet::new();
        for (i, v) in t.vars.iter().enumerate() {
            if seen.insert(v.name.clone()) {
                self.line(&format!("            {} => Some(self.v{i}.to_value()),", rust_str(&v.name)));
            }
        }
        self.line("            _ => None,");
        self.line("        }");
        self.line("    }");
        self.line("    fn vars(&self) -> Vec<(&'static str, Value)> {");
        let items: Vec<String> = t.vars.iter().enumerate().map(|(i, v)| format!("({}, self.v{i}.to_value())", rust_str(&v.name))).collect();
        self.line(&format!("        vec![{}]", items.join(", ")));
        self.line("    }");
        self.line("    fn lists(&self) -> Vec<(&'static str, Vec<Value>)> {");
        let items: Vec<String> = t.lists.iter().enumerate().map(|(i, l)| format!("({}, self.l{i}.values())", rust_str(&l.name))).collect();
        self.line(&format!("        vec![{}]", items.join(", ")));
        self.line("    }");
        self.line("    fn set_var(&mut self, index: usize, value: Value) {");
        self.line("        match index {");
        for i in 0..t.vars.len() {
            let r = self.an.repr(Node::Var(VarId { target: ti, index: i }));
            let conv = match r {
                Repr::Val => "value".to_string(),
                Repr::F64 => "<f64 as Elem>::from_value(&value)".to_string(),
                Repr::Bool => "<bool as Elem>::from_value(&value)".to_string(),
                Repr::Str => "value.to_str()".to_string(),
            };
            self.line(&format!("            {i} => self.v{i} = {conv},"));
        }
        self.line("            _ => {}");
        self.line("        }");
        self.line("    }");
        self.line("}");
        self.line("");

        // Scripts.
        for si in 0..t.scripts.len() {
            self.script_fn(ti, si);
        }
        // Procedure variants.
        for pi in 0..t.procs.len() {
            let id = ProcId { target: ti, index: pi };
            for warp in [false, true] {
                if self.an.variants.contains(&(id, warp)) {
                    self.proc_fn(id, warp);
                }
            }
        }
        let pending = std::mem::take(&mut self.pending);
        self.out.push_str(&pending);
        std::mem::take(&mut self.out)
    }

    fn script_fn(&mut self, ti: usize, si: usize) {
        let sc = &self.program.targets[ti].scripts[si];
        let owner = Owner::Script(ti, si);
        // Edge-activated hat predicate.
        match &sc.hat {
            Hat::GreaterThan { menu, value } => {
                let cx = Cx { owner, ti };
                let v = self.expr(value, &cx);
                self.line(&format!("pub fn t{ti}_s{si}_pred(w: &mut World, me: TargetRef) -> bool {{"));
                self.indent += 1;
                self.prologue(ti, false);
                self.indent -= 1;
                self.line(&format!("    let v_ = {};", v.num()));
                match menu.as_str() {
                    "timer" => self.line("    w.timer_value() > v_"),
                    "loudness" => self.line("    w.loudness(me) > v_"),
                    _ => self.line("    false"),
                }
                self.line("}");
                self.line("");
            }
            Hat::TouchingObject(obj) => {
                let cx = Cx { owner, ti };
                let v = self.expr(obj, &cx);
                self.line(&format!("pub fn t{ti}_s{si}_pred(w: &mut World, me: TargetRef) -> bool {{"));
                self.indent += 1;
                self.prologue(ti, false);
                self.indent -= 1;
                self.line(&format!("    let v_ = {};", v.val()));
                self.line("    w.touching_object(me, v_)");
                self.line("}");
                self.line("");
            }
            _ => {}
        }
        self.line(&format!("pub fn t{ti}_s{si}(me: TargetRef) -> BoxFut {{"));
        self.line("    Box::pin(async move {");
        self.indent += 2;
        self.prologue(ti, true);
        let mut fc = FnCx { cx: Cx { owner, ti }, warp: false, is_async: true, depth: 0, w_open: false, is_proc: false, in_part: false };
        let body = &self.program.targets[ti].scripts[si].body;
        self.emit_body(body, &mut fc, &format!("t{ti}_s{si}"), &[]);
        self.indent -= 2;
        self.line("    })");
        self.line("}");
        self.line("");
    }

    /// Emit a function body; bodies over the line limit are split into
    /// `<name>_partN` functions of consecutive top-level statements (3.3).
    fn emit_body(&mut self, body: &[Stmt], fc: &mut FnCx, name: &str, params: &[String]) {
        let start = self.out.len();
        self.stmts(body, fc, Tail::Fn);
        self.close_w(fc);
        let lines = self.out[start..].matches('\n').count();
        if lines <= self.opts.max_fn_lines || body.len() < 2 {
            return;
        }
        self.out.truncate(start);
        self.flow.clear();
        // Measure every top-level statement, then group greedily.
        let mut sizes = Vec::with_capacity(body.len());
        for s in body {
            let saved = std::mem::take(&mut self.out);
            self.flow.clear();
            self.stmt(s, fc, Tail::No);
            self.close_w(fc);
            sizes.push(self.out.matches('\n').count());
            self.out = saved;
        }
        let mut chunks: Vec<(usize, usize)> = Vec::new();
        let (mut begin, mut acc) = (0, 0);
        for (i, n) in sizes.iter().enumerate() {
            if acc > 0 && acc + n > self.opts.max_fn_lines {
                chunks.push((begin, i));
                begin = i;
                acc = 0;
            }
            acc += n;
        }
        chunks.push((begin, body.len()));
        let ti = fc.cx.ti;
        let sep = if params.is_empty() { "" } else { ", " };
        let args: String = (0..params.len()).map(|i| format!(", a{i}.clone()")).collect();
        let ret = if fc.is_proc { "return r_;" } else { "return;" };
        let outer_indent = self.indent;
        for (k, &(b, e)) in chunks.iter().enumerate() {
            let last = k + 1 == chunks.len();
            let saved = std::mem::take(&mut self.out);
            self.indent = 0;
            fc.in_part = true;
            if fc.is_async {
                self.line(&format!("fn {name}_part{k}(me: TargetRef{sep}{}) -> Pin<Box<dyn Future<Output = Option<bool>>>> {{", params.join(", ")));
                self.line("    Box::pin(async move {");
                self.indent = 2;
            } else {
                self.line(&format!("fn {name}_part{k}(w: &mut World, me: TargetRef{sep}{}) -> Option<bool> {{", params.join(", ")));
                self.indent = 1;
            }
            self.prologue(ti, fc.is_async);
            self.stmts(&body[b..e], fc, if last { Tail::Fn } else { Tail::No });
            self.close_w(fc);
            self.line("None");
            if fc.is_async {
                self.indent = 0;
                self.line("    })");
            }
            self.indent = 0;
            self.line("}");
            self.line("");
            fc.in_part = false;
            let part = std::mem::replace(&mut self.out, saved);
            self.pending.push_str(&part);
            self.indent = outer_indent;
            if fc.is_async {
                self.line(&format!("if let Some(r_) = {name}_part{k}(me{args}).await {{ {ret} }}"));
            } else {
                self.line(&format!("if let Some(r_) = {name}_part{k}(w, me{args}) {{ {ret} }}"));
            }
        }
        self.flow.clear();
    }

    /// Variables assigned anywhere in `body`; `None` when a call makes that unknowable.
    fn written_vars(body: &[Stmt]) -> Option<Vec<VarId>> {
        let mut out = Vec::new();
        let mut unknown = false;
        walk_stmts(body, &mut |s| match s {
            Stmt::SetVar(v, _) | Stmt::ChangeVar(v, _) | Stmt::ForEach(v, _, _) => out.push(*v),
            Stmt::Call { .. } => unknown = true,
            _ => {}
        });
        if unknown {
            None
        } else {
            Some(out)
        }
    }

    /// Forget flow facts invalidated by executing `body` an unknown number of times.
    fn flow_kill(&mut self, body: &[Stmt]) {
        match Self::written_vars(body) {
            Some(vars) => {
                for v in vars {
                    self.flow.remove(&v);
                }
            }
            None => self.flow.clear(),
        }
    }

    /// Record what a variable holds after an assignment.
    fn flow_set(&mut self, v: VarId, ty: scrust_analysis::Ty, fc: &FnCx) {
        // Only this target's own instance (or the stage) is tracked.
        let own = v.target == 0 || v.target == fc.cx.ti;
        if own && self.an.repr(Node::Var(v)) == Repr::Val && !ty.is_empty() {
            self.flow.insert(v, ty);
        } else {
            self.flow.remove(&v);
        }
    }

    /// Cache pointers to the variable storage this function can reach.
    fn prologue(&mut self, ti: usize, is_async: bool) {
        self.flow.clear();
        let w = if is_async { "world()" } else { "w" };
        self.line(&format!("let g = {w}.globals_ptr::<L0>();"));
        if ti != 0 {
            self.line(&format!("let l = {w}.locals_ptr::<L{ti}>(me);"));
        }
    }

    fn proc_name(&self, id: ProcId, warp: bool) -> String {
        format!("t{}_p{}_{}", id.target, id.index, if warp { "w" } else { "n" })
    }

    fn proc_is_async(&self, id: ProcId, warp: bool) -> bool {
        self.an.yields.get(&(id, warp)).copied().unwrap_or(true)
    }

    fn proc_fn(&mut self, id: ProcId, warp: bool) {
        let pr = &self.program.targets[id.target].procs[id.index];
        let is_async = self.proc_is_async(id, warp);
        let name = self.proc_name(id, warp);
        let params: Vec<String> =
            (0..pr.params.len()).map(|i| format!("a{}: {}", i, repr_ty(self.an.repr(Node::Param(id, i))))).collect();
        self.line(&format!("/// {}{}", pr.proccode.replace('\n', " "), if warp { " (warp)" } else { "" }));
        let mut fc = FnCx { cx: Cx { owner: Owner::Proc(id), ti: id.target }, warp, is_async, depth: 0, w_open: false, is_proc: true, in_part: false };
        if is_async {
            let sep = if params.is_empty() { "" } else { ", " };
            self.line(&format!("pub fn {name}(me: TargetRef{sep}{}) -> Pin<Box<dyn Future<Output = bool>>> {{", params.join(", ")));
            self.line("    Box::pin(async move {");
            self.indent += 2;
            self.prologue(id.target, true);
            self.emit_body(&pr.body, &mut fc, &name, &params);
            self.line("false");
            self.indent -= 2;
            self.line("    })");
            self.line("}");
        } else {
            let sep = if params.is_empty() { "" } else { ", " };
            self.line(&format!("pub fn {name}(w: &mut World, me: TargetRef{sep}{}) -> bool {{", params.join(", ")));
            self.indent += 1;
            self.prologue(id.target, false);
            self.emit_body(&pr.body, &mut fc, &name, &params);
            self.line("false");
            self.indent -= 1;
            self.line("}");
        }
        self.line("");
    }

    // -------------------------------------------------------------- statements

    fn open_w(&mut self, fc: &mut FnCx) {
        if fc.is_async && !fc.w_open {
            self.line("{");
            self.indent += 1;
            self.line("let mut wg_ = world();");
            self.line("let w = &mut *wg_;");
            fc.w_open = true;
        }
    }

    fn close_w(&mut self, fc: &mut FnCx) {
        if fc.w_open {
            self.indent -= 1;
            self.line("}");
            fc.w_open = false;
        }
    }

    /// Evaluate `code` with world access and bind it to a fresh variable that
    /// outlives the world borrow.
    fn bind(&mut self, fc: &mut FnCx, prefix: &str, code: &str) -> String {
        let name = format!("{}{}", prefix, self.fresh());
        if fc.is_async {
            self.close_w(fc);
            self.line(&format!("let {name} = {{ let mut wg_ = world(); let w = &mut *wg_; {code} }};"));
        } else {
            self.line(&format!("let {name} = {code};"));
        }
        name
    }

    /// Emit `let _ = expr;` for expressions whose evaluation is observable.
    fn discard(&mut self, exprs: &[&Expr], fc: &mut FnCx) {
        for e in exprs {
            if e.is_impure() {
                self.open_w(fc);
                let x = self.expr(e, &fc.cx);
                self.line(&format!("let _ = {};", x.val()));
            }
        }
    }

    fn may_yield(&self, s: &Stmt, fc: &FnCx) -> bool {
        fc.is_async && self.an.stmt_may_yield(self.program, s, fc.warp)
    }

    /// Does the body contain something that can set the skip-loop-yield flag?
    fn has_promise(&self, body: &[Stmt]) -> bool {
        let mut hit = false;
        walk_stmts(body, &mut |s| match s {
            Stmt::SayForSecs { .. } | Stmt::Ask(_) | Stmt::PlaySoundUntilDone(_) => hit = true,
            Stmt::Call { proc, .. } if self.an.promise_tail.contains(proc) => hit = true,
            _ => {}
        });
        hit
    }

    fn stmts(&mut self, body: &[Stmt], fc: &mut FnCx, tail: Tail) {
        let n = body.len();
        for (i, s) in body.iter().enumerate() {
            let t = if i + 1 == n { tail } else { Tail::No };
            self.stmt(s, fc, t);
        }
    }

    /// Emit the yield at the end of a loop iteration.
    fn loop_end(&mut self, body: &[Stmt], fc: &mut FnCx) {
        if !fc.is_async {
            return;
        }
        self.close_w(fc);
        if !fc.warp {
            self.line("yield_loop().await;");
        } else {
            if self.has_promise(body) {
                self.line("world().set_skip_loop_yield(false);");
            }
            if self.opts.warp_timer {
                self.line("if world().warp_stuck() { yield_now().await; }");
            }
        }
    }

    /// The (possibly busy-waiting) yield of a re-executing block.
    fn yield_retry(&mut self, fc: &mut FnCx) {
        self.close_w(fc);
        if fc.warp {
            self.line("if world().warp_stuck() { yield_now().await; }");
        } else {
            self.line("yield_now().await;");
        }
    }

    fn promise_done(&mut self, fc: &mut FnCx, tail: Tail) {
        if tail != Tail::No {
            self.line("world().set_skip_loop_yield(true);");
        }
        let _ = fc;
    }

    fn stmt(&mut self, s: &Stmt, fc: &mut FnCx, tail: Tail) {
        let asyncy = self.may_yield(s, fc);
        let is_loop = matches!(s, Stmt::Repeat(..) | Stmt::Forever(_) | Stmt::RepeatUntil(..) | Stmt::While(..) | Stmt::ForEach(..));
        if is_loop {
            // The loop head is reached again after the body ran.
            if asyncy {
                self.flow.clear();
            } else if let Some(b) = s.bodies().first() {
                self.flow_kill(b);
            }
            if let Stmt::ForEach(v, _, _) = s {
                self.flow.remove(v);
            }
        }
        self.stmt_inner(s, fc, tail, asyncy);
        if asyncy || matches!(s, Stmt::Call { .. }) {
            // Other threads (or the callee) may have written anything.
            self.flow.clear();
        } else if is_loop {
            if let Some(b) = s.bodies().first() {
                self.flow_kill(b);
            }
            if let Stmt::ForEach(v, _, _) = s {
                self.flow.remove(v);
            }
        }
    }

    fn stmt_inner(&mut self, s: &Stmt, fc: &mut FnCx, tail: Tail, asyncy: bool) {
        match s {
            Stmt::SetVar(v, e) => {
                self.open_w(fc);
                let x = self.expr(e, &fc.cx);
                let r = self.an.repr(Node::Var(*v));
                let place = self.var_place(*v, &fc.cx, false, true);
                self.line(&format!("{{ let t_ = {}; {} = t_; }}", x.as_repr(r), place));
                let ty = if x.missing { scrust_analysis::Ty::STR_NAN } else { x.ty };
                self.flow_set(*v, ty, fc);
            }
            Stmt::ChangeVar(v, e) => {
                self.open_w(fc);
                let x = self.expr(e, &fc.cx);
                let r = self.an.repr(Node::Var(*v));
                let place = self.var_place(*v, &fc.cx, false, true);
                let cur = self.expr(&Expr::Var(*v), &fc.cx);
                match r {
                    Repr::F64 => self.line(&format!("{{ let d_ = {}; let p_ = &mut {}; *p_ = {} + d_; }}", x.num(), place, E { code: "*p_".into(), place: None, ..cur }.num())),
                    Repr::Val => self.line(&format!("{{ let d_ = {}; let p_ = &mut {}; *p_ = Value::Num(p_.to_num() + d_); }}", x.num(), place)),
                    // The analysis types a changed variable as a number, so
                    // other representations cannot be chosen for it.
                    Repr::Str | Repr::Bool => self.line(&format!("{{ let d_ = {}; let _ = d_; }}", x.num())),
                }
                let ty = scrust_analysis::ty::arith(Op::Add, cur.ty, x.ty);
                self.flow_set(*v, ty, fc);
            }
            Stmt::ShowVar(v, show) => {
                self.open_w(fc);
                self.line(&format!("w.set_monitor_visible({}, false, {}, {});", v.target, v.index, show));
            }
            Stmt::ShowList(l, show) => {
                self.open_w(fc);
                self.line(&format!("w.set_monitor_visible({}, true, {}, {});", l.target, l.index, show));
            }
            Stmt::ListAdd(l, e) => {
                self.open_w(fc);
                let x = self.expr(e, &fc.cx);
                let r = self.an.repr(Node::List(*l));
                let place = self.list_place(*l, &fc.cx, true);
                self.line(&format!("{{ let t_ = {}; {}.add(t_); }}", x.as_repr(r), place));
            }
            Stmt::ListDelete(l, idx) => {
                self.open_w(fc);
                let i = self.expr(idx, &fc.cx);
                let place = self.list_place(*l, &fc.cx, true);
                let rplace = self.list_place(*l, &fc.cx, false);
                let (pre, ix) = self.list_index(&i, &rplace, 0, true);
                self.line(&format!("{{ {} let ix_ = {}; {}.delete(ix_); }}", pre, ix, place));
            }
            Stmt::ListDeleteAll(l) => {
                self.open_w(fc);
                let place = self.list_place(*l, &fc.cx, true);
                self.line(&format!("{}.delete_all();", place));
            }
            Stmt::ListInsert(l, idx, item) => {
                self.open_w(fc);
                let x = self.expr(item, &fc.cx);
                let i = self.expr(idx, &fc.cx);
                let r = self.an.repr(Node::List(*l));
                let place = self.list_place(*l, &fc.cx, true);
                let rplace = self.list_place(*l, &fc.cx, false);
                let (pre, ix) = self.list_index(&i, &rplace, 1, false);
                self.line(&format!("{{ let t_ = {}; {} let ix_ = {}; {}.insert(ix_, t_); }}", x.as_repr(r), pre, ix, place));
            }
            Stmt::ListReplace(l, idx, item) => {
                self.open_w(fc);
                let i = self.expr(idx, &fc.cx);
                let x = self.expr(item, &fc.cx);
                let r = self.an.repr(Node::List(*l));
                let place = self.list_place(*l, &fc.cx, true);
                let rplace = self.list_place(*l, &fc.cx, false);
                let (pre, ix) = self.list_index(&i, &rplace, 0, false);
                // Inputs are evaluated first (in block order); the index is
                // resolved (possibly drawing a random number) when the block runs.
                self.line(&format!("{{ {} let t_ = {}; let ix_ = {}; {}.replace(ix_, t_); }}", pre, x.as_repr(r), ix, place));
            }
            Stmt::Cmd(cmd, args, order) => {
                self.open_w(fc);
                let mut codes: Vec<String> = Vec::new();
                for (spec, a) in cmd.args().iter().zip(args) {
                    codes.push(match spec {
                        A::Field(_) => match a {
                            Expr::Lit(v) => rust_str(&v.to_str().to_rust_string()),
                            _ => "\"\"".into(),
                        },
                        A::In(_, k) => {
                            let x = self.expr(a, &fc.cx);
                            cast(&x, *k)
                        }
                    });
                }
                let mut lets = String::new();
                for &i in order {
                    let _ = write!(lets, "let c{} = {}; ", i, codes[i]);
                }
                let names: String = (0..codes.len()).map(|i| format!(", c{}", i)).collect();
                self.line(&format!("{{ {}w.{}(me{}); }}", lets, cmd.method(), names));
            }
            Stmt::Discard(args) => {
                let refs: Vec<&Expr> = args.iter().collect();
                self.discard(&refs, fc);
            }
            Stmt::StopOtherScripts => {
                self.open_w(fc);
                self.line("w.stop_other_scripts(me);");
            }
            Stmt::StopThisScript => {
                self.open_w(fc);
                self.line(match (fc.in_part, fc.is_proc) {
                    (true, _) => "return Some(true);",
                    (false, true) => "return true;",
                    (false, false) => "return;",
                });
            }
            Stmt::StopAll => {
                self.close_w(fc);
                self.line("world().stop_all();");
                self.line("die().await;");
            }
            Stmt::DeleteThisClone => {
                self.close_w(fc);
                self.line("if world().delete_this_clone(me) { die().await; }");
            }
            Stmt::Broadcast(b) => {
                self.open_w(fc);
                match b {
                    BroadcastRef::Static(m) => self.line(&format!("w.broadcast({});", m)),
                    BroadcastRef::Nothing => {}
                    BroadcastRef::Dynamic(e) => {
                        let x = self.expr(e, &fc.cx);
                        self.line(&format!("{{ let n_ = {}; w.broadcast_dynamic(n_); }}", x.str()));
                    }
                }
            }
            Stmt::If(c, a, b) => {
                let cond = self.expr(c, &fc.cx).bool();
                if asyncy {
                    let cv = self.bind(fc, "c", &cond);
                    self.line(&format!("if {cv} {{"));
                } else {
                    self.open_w(fc);
                    self.line(&format!("if {cond} {{"));
                }
                let before = self.flow.clone();
                self.branch(a, fc, tail);
                let after_a = std::mem::replace(&mut self.flow, before);
                if !b.is_empty() {
                    self.line("} else {");
                    self.branch(b, fc, tail);
                }
                self.line("}");
                // Join: keep what both paths agree on, as the union of types.
                let after_b = std::mem::take(&mut self.flow);
                for (v, ta) in after_a {
                    if let Some(tb) = after_b.get(&v) {
                        self.flow.insert(v, ta | *tb);
                    }
                }
            }
            Stmt::Repeat(times, body) => {
                let x = self.expr(times, &fc.cx);
                let code = format!("js_round({})", x.num());
                let n = if asyncy {
                    self.bind(fc, "n", &code)
                } else {
                    self.open_w(fc);
                    let name = format!("n{}", self.fresh());
                    self.line(&format!("let {name} = {code};"));
                    name
                };
                self.line(&format!("let mut {n} = {n};"));
                self.line("loop {");
                self.indent += 1;
                self.line(&format!("{n} -= 1.0;"));
                self.line(&format!("if !({n} >= 0.0) {{ break; }}"));
                self.loop_body(body, fc, asyncy);
                // The block is re-executed (inputs included) on every iteration.
                self.discard(&[times], fc);
                self.end_loop(fc, asyncy);
            }
            Stmt::Forever(body) => {
                if asyncy {
                    self.close_w(fc);
                } else {
                    self.open_w(fc);
                }
                self.line("loop {");
                self.indent += 1;
                self.loop_body(body, fc, asyncy);
                self.end_loop(fc, asyncy);
            }
            Stmt::RepeatUntil(c, body) | Stmt::While(c, body) => {
                let until = matches!(s, Stmt::RepeatUntil(..));
                if asyncy {
                    self.close_w(fc);
                } else {
                    self.open_w(fc);
                }
                self.line("loop {");
                self.indent += 1;
                let cond = self.expr(c, &fc.cx).bool();
                let test = if until { String::new() } else { "!".to_string() };
                if asyncy {
                    let cv = self.bind(fc, "c", &cond);
                    self.line(&format!("if {test}{cv} {{ break; }}"));
                } else {
                    self.line(&format!("if {test}{cond} {{ break; }}"));
                }
                self.loop_body(body, fc, asyncy);
                self.end_loop(fc, asyncy);
            }
            Stmt::ForEach(v, value, body) => {
                let k = self.fresh();
                if asyncy {
                    self.close_w(fc);
                } else {
                    self.open_w(fc);
                }
                self.line(&format!("let mut fe{k} = 0.0_f64;"));
                self.line("loop {");
                self.indent += 1;
                let lim = self.expr(value, &fc.cx).js_number();
                let r = self.an.repr(Node::Var(*v));
                let place = self.var_place(*v, &fc.cx, false, true);
                let store = E::new(format!("fe{k}"), RT::Num, scrust_analysis::Ty::POS_INT).as_repr(r);
                self.open_w(fc);
                self.line(&format!("let lim_ = {lim};"));
                self.line(&format!("if !(fe{k} < lim_) {{ break; }}"));
                self.line(&format!("fe{k} += 1.0;"));
                self.line(&format!("{place} = {store};"));
                self.loop_body(body, fc, asyncy);
                self.end_loop(fc, asyncy);
            }
            Stmt::Wait(secs) => {
                let x = self.expr(secs, &fc.cx).num();
                let tm = self.bind(fc, "tm", &format!("{{ let s_ = {x}; w.wait_begin(s_) }}"));
                if !fc.warp {
                    self.line("yield_now().await;");
                }
                self.line("loop {");
                self.indent += 1;
                self.discard(&[secs], fc);
                let done = self.bind(fc, "d", &format!("w.wait_done({tm})"));
                self.line(&format!("if {done} {{ break; }}"));
                self.yield_retry(fc);
                self.indent -= 1;
                self.line("}");
            }
            Stmt::WaitUntil(c) => {
                self.close_w(fc);
                self.line("loop {");
                self.indent += 1;
                let cond = self.expr(c, &fc.cx).bool();
                let cv = self.bind(fc, "c", &cond);
                self.line(&format!("if {cv} {{ break; }}"));
                self.yield_retry(fc);
                self.indent -= 1;
                self.line("}");
            }
            Stmt::BroadcastAndWait(b) => {
                let start = match b {
                    BroadcastRef::Static(m) => format!("w.broadcast({})", m),
                    BroadcastRef::Nothing => "Vec::<u64>::new()".to_string(),
                    BroadcastRef::Dynamic(e) => {
                        let x = self.expr(e, &fc.cx);
                        format!("{{ let n_ = {}; w.broadcast_dynamic(n_) }}", x.str())
                    }
                };
                let th = self.bind(fc, "th", &start);
                let again: Vec<&Expr> = match b {
                    BroadcastRef::Dynamic(e) => vec![e],
                    _ => vec![],
                };
                self.wait_threads(&th, &again, fc);
            }
            Stmt::SwitchBackdropAndWait(e) => {
                let x = self.expr(e, &fc.cx);
                let th = self.bind(fc, "th", &format!("{{ let v_ = {}; w.switch_backdrop_threads(v_) }}", x.val()));
                // Bug-compatible with scratch-vm: starting hats here aborts the tick.
                self.line(&format!("if !{th}.is_empty() {{ world().abort_tick(); yield_now().await; }}"));
                self.wait_threads(&th, &[e], fc);
            }
            Stmt::Glide { secs, x, y } => {
                let (cs, cx_, cy) = (self.expr(secs, &fc.cx).num(), self.expr(x, &fc.cx).num(), self.expr(y, &fc.cx).num());
                let g = self.bind(fc, "g", &format!("{{ let s_ = {cs}; let x_ = {cx_}; let y_ = {cy}; w.glide_begin(me, s_, x_, y_) }}"));
                self.line(&format!("if let Some({g}) = {g} {{"));
                self.indent += 1;
                self.line("loop {");
                self.indent += 1;
                self.yield_retry(fc);
                self.discard(&[secs, x, y], fc);
                let d = self.bind(fc, "d", &format!("w.glide_step(me, &{g})"));
                self.line(&format!("if {d} {{ break; }}"));
                self.indent -= 1;
                self.line("}");
                self.indent -= 1;
                self.line("}");
            }
            Stmt::GlideTo { secs, to } => {
                let cs = self.expr(secs, &fc.cx).num();
                let ct = self.expr(to, &fc.cx).val();
                // `getTargetXY` runs again on every re-execution (it may draw random numbers).
                let dynamic_to = !matches!(to, Expr::Lit(Value::Str(s)) if !s.eq_str("_random_"));
                let g = self.bind(
                    fc,
                    "g",
                    &format!("{{ let s_ = {cs}; let t_ = {ct}; match w.target_xy(&t_) {{ Some((x_, y_)) => w.glide_begin(me, s_, x_, y_), None => None }} }}"),
                );
                self.line(&format!("if let Some({g}) = {g} {{"));
                self.indent += 1;
                self.line("loop {");
                self.indent += 1;
                self.yield_retry(fc);
                self.discard(&[secs], fc);
                let step = if dynamic_to {
                    format!("{{ let t_ = {ct}; match w.target_xy(&t_) {{ Some(_) => w.glide_step(me, &{g}), None => true }} }}")
                } else {
                    format!("w.glide_step(me, &{g})")
                };
                let d = self.bind(fc, "d", &step);
                self.line(&format!("if {d} {{ break; }}"));
                self.indent -= 1;
                self.line("}");
                self.indent -= 1;
                self.line("}");
            }
            Stmt::SayForSecs { think, message, secs } => {
                let m = self.expr(message, &fc.cx).val();
                let sc = self.expr(secs, &fc.cx).val();
                let wk = self.bind(fc, "wk", &format!("{{ let m_ = {m}; let s_ = {sc}; w.say_for_secs(me, {think}, m_, s_) }}"));
                self.line(&format!("wait_external({wk}).await;"));
                self.promise_done(fc, tail);
            }
            Stmt::Ask(q) => {
                // `String(args.QUESTION)`
                let c = self.expr(q, &fc.cx).str();
                let wk = self.bind(fc, "wk", &format!("{{ let q_ = {c}; w.ask(me, q_) }}"));
                self.line(&format!("wait_external({wk}).await;"));
                self.promise_done(fc, tail);
            }
            Stmt::PlaySoundUntilDone(e) => {
                let c = self.expr(e, &fc.cx).val();
                let wk = self.bind(fc, "wk", &format!("{{ let s_ = {c}; w.sound_play_until_done(me, s_) }}"));
                self.line(&format!("if let Some({wk}) = {wk} {{"));
                self.indent += 1;
                self.line(&format!("wait_external({wk}).await;"));
                self.promise_done(fc, tail);
                self.indent -= 1;
                self.line("}");
            }
            Stmt::Call { proc, args, order } => self.call(*proc, args, order, fc, tail),
        }
    }

    fn branch(&mut self, body: &[Stmt], fc: &mut FnCx, tail: Tail) {
        self.indent += 1;
        let outer_open = fc.w_open;
        fc.depth += 1;
        self.stmts(body, fc, tail);
        fc.depth -= 1;
        // A branch must leave the world block exactly as it found it.
        if !outer_open {
            self.close_w(fc);
        }
        self.indent -= 1;
    }

    fn loop_body(&mut self, body: &[Stmt], fc: &mut FnCx, asyncy: bool) {
        let outer_open = fc.w_open;
        fc.depth += 1;
        self.stmts(body, fc, Tail::Loop);
        fc.depth -= 1;
        if asyncy {
            self.loop_end(body, fc);
        } else if !outer_open {
            self.close_w(fc);
        }
    }

    fn end_loop(&mut self, fc: &mut FnCx, asyncy: bool) {
        if asyncy {
            self.close_w(fc);
        }
        self.indent -= 1;
        self.line("}");
    }

    /// The waiting half of `broadcast and wait` / `switch backdrop and wait`.
    fn wait_threads(&mut self, th: &str, again: &[&Expr], fc: &mut FnCx) {
        self.line(&format!("if !{th}.is_empty() {{"));
        self.indent += 1;
        self.line("let mut first_ = true;");
        self.line("loop {");
        self.indent += 1;
        if again.iter().any(|e| e.is_impure()) {
            self.line("if !first_ {");
            self.indent += 1;
            self.discard(again, fc);
            self.close_w(fc);
            self.indent -= 1;
            self.line("}");
        }
        self.line("first_ = false;");
        self.line(&format!("let st_ = world().wait_threads_status(&{th});"));
        self.line("match st_ {");
        self.line("    None => break,");
        if fc.warp {
            self.line("    Some(Status::YieldTick) => yield_tick().await,");
            self.line("    Some(_) => { if world().warp_stuck() { yield_now().await; } }");
        } else {
            self.line("    Some(s_) => yield_status(s_).await,");
        }
        self.line("}");
        self.indent -= 1;
        self.line("}");
        self.indent -= 1;
        self.line("}");
    }

    fn call(&mut self, proc: ProcId, args: &[Expr], order: &[usize], fc: &mut FnCx, tail: Tail) {
        let p = self.program;
        let callee_warp = self.an.callee_warp(p, proc, fc.warp);
        let callee_async = self.proc_is_async(proc, callee_warp);
        let name = self.proc_name(proc, callee_warp);
        let k = self.fresh();
        let mut codes: Vec<String> = Vec::new();
        for (i, a) in args.iter().enumerate() {
            let x = self.expr(a, &fc.cx);
            codes.push(x.as_repr(self.an.repr(Node::Param(proc, i))));
        }
        let names: String = (0..args.len()).map(|i| format!(", p{k}_{i}")).collect();
        let impure: Vec<&Expr> = args.iter().filter(|a| a.is_impure()).collect();
        if !callee_async {
            self.open_w(fc);
            for &i in order {
                self.line(&format!("let p{k}_{i} = {};", codes[i]));
            }
            if impure.is_empty() {
                self.line(&format!("{name}(w, me{names});"));
            } else {
                // A `stop this script` inside re-executes the call block's inputs.
                self.line(&format!("if {name}(w, me{names}) {{"));
                self.indent += 1;
                self.discard(&impure, fc);
                self.indent -= 1;
                self.line("}");
            }
            return;
        }
        // Asynchronous callee: arguments first, then the call outside of any world borrow.
        self.close_w(fc);
        for i in 0..args.len() {
            self.line(&format!("let p{k}_{i};"));
        }
        if !args.is_empty() {
            self.line("{");
            self.indent += 1;
            self.line("let mut wg_ = world();");
            self.line("let w = &mut *wg_;");
            for &i in order {
                self.line(&format!("p{k}_{i} = {};", codes[i]));
            }
            self.indent -= 1;
            self.line("}");
        }
        // Non-warp calls into a recursive procedure yield when the call is
        // recursive (scratch-vm `isRecursiveCall`).
        let track = !callee_warp && self.an.cyclic.contains(&proc);
        if track {
            let uid = (proc.target as u32) << 16 | proc.index as u32;
            self.line(&format!("if world().enter_call({}, {}) {{ yield_now().await; }}", uid, fc.depth.min(200)));
        }
        if impure.is_empty() {
            self.line(&format!("{name}(me{names}).await;"));
        } else {
            self.line(&format!("if {name}(me{names}).await {{"));
            self.indent += 1;
            self.discard(&impure, fc);
            self.close_w(fc);
            self.indent -= 1;
            self.line("}");
        }
        if track {
            self.line("world().exit_call();");
        }
        if tail == Tail::No && self.an.promise_tail.contains(&proc) {
            self.line("world().set_skip_loop_yield(false);");
        }
    }
}

#[allow(dead_code)]
fn _unused(_: &Value) -> (String, String) {
    (val_lit(&Value::Num(0.0)), str_lit(&scrust_value::JsStr::empty()))
}
